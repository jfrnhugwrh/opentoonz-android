extern "C" {

// The font handles are opaque tokens; the identity only has to be stable.
void *glutStrokeRoman     = (void *)"stroke_roman";
void *glutStrokeMonoRoman = (void *)"stroke_mono_roman";
void *glutBitmap9By15     = (void *)"bitmap_9_by_15";
void *glutBitmap8By13     = (void *)"bitmap_8_by_13";
void *glutBitmapTimesRoman10  = (void *)"bitmap_times_10";
void *glutBitmapTimesRoman24  = (void *)"bitmap_times_24";
void *glutBitmapHelvetica10   = (void *)"bitmap_helvetica_10";
void *glutBitmapHelvetica12   = (void *)"bitmap_helvetica_12";
void *glutBitmapHelvetica18   = (void *)"bitmap_helvetica_18";

//! GLUT initialisation is a no-op on Android: there is no GLUT window system
//! and the viewer widget owns the context.
void glutInit(int *, char **) {}

//! Emits one glyph as a set of quads covering the dot matrix cell, then moves
//! the pen to the next character.  As with the real GLUT stroke font the
//! geometry is generated between glBegin()/glEnd() and the pen advance is
//! accumulated in the modelview matrix, so the call is transparent to callers
//! that simply loop over the characters of a string.
void glutStrokeCharacter(void *font, int character) {
  if (!font) return;
  const unsigned char *g = glyphFor(character);
  if (!g) return;

  glBegin(GL_QUADS);
  for (int col = 0; col < kGlyphCols; ++col) {
    for (int row = 0; row < kGlyphRows; ++row) {
      if (((g[col] >> row) & 1) == 0) continue;

      const double x0 = col * kUnitScale;
      const double y0 = row * kUnitScale;
      const double x1 = x0 + kUnitScale;
      const double y1 = y0 + kUnitScale;

      glVertex2d(x0, y0);
      glVertex2d(x1, y0);
      glVertex2d(x1, y1);
      glVertex2d(x0, y1);
    }
  }
  glEnd();

  glTranslated(kAdvance, 0.0, 0.0);
}

//! Width of one glyph in font units; the caller normalises by the em size.
int glutStrokeWidth(void *font, int character) {
  if (!font || !glyphFor(character)) return 0;
  return (int)kAdvance;
}

void glutBitmapCharacter(void *font, int character) {
  glutStrokeCharacter(font, character);
}

int glutBitmapWidth(void *font, int character) {
  return glutStrokeWidth(font, character);
}

}  // extern "C"

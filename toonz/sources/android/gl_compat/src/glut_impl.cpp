const int kGlyphCols = 5;
const int kGlyphRows = 7;

//! Scale of one dot matrix cell, chosen so that a glyph is as tall as (and
//! advances like) the GLUT stroke roman font the desktop build uses; callers
//! multiply the returned pen advance by the same 0.07 em factor as before, so
//! rendered text keeps its original size.
const double kUnitScale = 152.0 / kGlyphRows;
const double kAdvance   = kGlyphCols * kUnitScale;

const unsigned char *glyphFor(int character) {
  if (character < 32 || character > 126) return nullptr;
  return kFont5x7[character - 32];
}


//=============================================================================
//
//  Android OpenGL ES compatibility layer - GLUT subset.
//
//  TnzCore draws text inside the OpenGL viewer through the GLUT stroke font
//  (tglDrawText / tglGetTextWidth), and OverallDesigner uses the bitmap
//  variant.  GLUT is a windowing toolkit and is not available on Android, so
//  the small subset the renderer relies upon is re-implemented here on top of
//  the fixed function emulation.
//
//  The stroke font is a compact single stroke face: every glyph is described
//  by a 5x7 dot matrix and emitted as filled unit quads, which keeps the
//  geometry in the same 1/70 em grid the original code scales against.  This
//  reproduces exactly what the renderer needs - a readable, scalable, vector
//  text - without pulling in the full GLUT font tables.
//
//=============================================================================

